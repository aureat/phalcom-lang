macro_rules! surface_record {
    (
        owner = $owner:ident,
        side = $side:ident,
        selector = $selector:literal,
        kind = $kind:ident,
        visibility = $vis:ident,
        callable = $callable:ident,
        params = $params:ident,
        returns = $returns:ident,
        effects = $effects:expr,
        raises = $raises:expr,
        flow = $flow:expr,
        intrinsic = $intrinsic:expr,
        return_shape = $shape:expr,
        docs = $docs:expr
    ) => {
        NativeSurfaceRecord {
            surface: PrimitiveSurfaceSpec {
                key: PrimitiveKey {
                    owner: UniverseKey::$owner,
                    side: NativeDispatch::$side,
                    selector: $selector,
                },
                visibility: NativeVisibility::$vis,
                stability: NativeStability::Stable,
                params: &$params,
                returns: &$returns,
                callable: &$callable,
                raises: $raises,
                effects: $effects,
                flow: $flow,
                since: None,
                deprecated_since: None,
                replacement: None,
                lifecycle: NativeLifecycleSpec::UNKNOWN,
                intrinsic: $intrinsic,
                trust: NativeTrust::Ordinary,
                docs: $docs,
                conceptual: None,
            },
            kind: NativeMemberKind::$kind,
            abi: PrimitiveAbi::Value,
            return_shape: $shape,
        }
    };
}

