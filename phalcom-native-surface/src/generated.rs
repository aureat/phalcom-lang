macro_rules! define_callable {
    ($name:ident, $params:ident, $ret:ident) => {
        pub static $name: CallableTypeSpec = CallableTypeSpec {
            type_params: &[],
            params: &$params,
            return_type: &$ret,
        };
    };
}

