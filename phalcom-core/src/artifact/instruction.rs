//! Exhaustive adapters between the VM instruction set and portable wire code.
//!
//! These adapters relocate no objects. Table indices remain prototype-local;
//! the full executable validator must check them before VM installation.

use crate::bytecode::{Bytecode, FamilySpecKind, PackAccess, PackSendKind};
use phalcom_compiler_artifact::executable::instruction::{PortableAccessV1, PortableFamilyKindV1, PortableInstructionV1, PortableSendKindV1};

impl From<FamilySpecKind> for PortableFamilyKindV1 {
    fn from(value: FamilySpecKind) -> Self {
        match value {
            FamilySpecKind::Exact => Self::Exact,
            FamilySpecKind::Pattern => Self::Pattern,
        }
    }
}

impl From<PortableFamilyKindV1> for FamilySpecKind {
    fn from(value: PortableFamilyKindV1) -> Self {
        match value {
            PortableFamilyKindV1::Exact => Self::Exact,
            PortableFamilyKindV1::Pattern => Self::Pattern,
        }
    }
}

impl From<PackSendKind> for PortableSendKindV1 {
    fn from(value: PackSendKind) -> Self {
        match value {
            PackSendKind::Method => Self::Method,
            PackSendKind::SubscriptGet => Self::SubscriptGet,
            PackSendKind::SubscriptSet => Self::SubscriptSet,
        }
    }
}

impl From<PortableSendKindV1> for PackSendKind {
    fn from(value: PortableSendKindV1) -> Self {
        match value {
            PortableSendKindV1::Method => Self::Method,
            PortableSendKindV1::SubscriptGet => Self::SubscriptGet,
            PortableSendKindV1::SubscriptSet => Self::SubscriptSet,
        }
    }
}

impl From<PackAccess> for PortableAccessV1 {
    fn from(value: PackAccess) -> Self {
        match value {
            PackAccess::Ordinary => Self::Ordinary,
            PackAccess::CompilerInternal => Self::CompilerInternal,
        }
    }
}

impl From<PortableAccessV1> for PackAccess {
    fn from(value: PortableAccessV1) -> Self {
        match value {
            PortableAccessV1::Ordinary => Self::Ordinary,
            PortableAccessV1::CompilerInternal => Self::CompilerInternal,
        }
    }
}

